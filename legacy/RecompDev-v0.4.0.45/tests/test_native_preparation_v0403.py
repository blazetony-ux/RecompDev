"""Native preparation source integrity, Ghidra-bounded Z80 and browser action."""
import hashlib
import json
import os
import shutil
import sqlite3
import socket
import subprocess
import sys
import tempfile
import time
import unittest
from unittest.mock import patch
from pathlib import Path
from urllib.request import Request,urlopen
from urllib.error import HTTPError

ROOT=Path(__file__).resolve().parents[1]
from discovery.store import connect,store_source
from nativeprep.engine import prepare,sha256

class NativePrepTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.addCleanup(self.temp.cleanup)
        self.dir=Path(self.temp.name);self.roms=self.dir/'roms';self.roms.mkdir()
        self.sms=self.roms/'Shinobi (test).sms'
        image=bytearray([0]*0x10000)
        image[0:5]=bytes.fromhex('3e01c30000') # LD A,1; JP 0
        image[0x7ff0:0x7ff8]=b'TMR SEGA'
        self.sms.write_bytes(image)
        self.digest=sha256(self.sms)
        self.db=self.dir/'db.sqlite';shutil.copyfile(ROOT/'catalogue.sqlite',self.db)
        c=connect(self.db);store_source(c,self.digest,self.sms,len(image),'SHA256_COMPLETE','mastersystem','Shinobi','Sega 8-bit header');c.close()

    def test_01_registration_even_without_ghidra(self):
        result=prepare(self.db,self.digest,self.dir/'output',allowed_roots=[self.roms],analyze=False)
        self.assertEqual(result['status'],'REGISTERED_NEEDS_ANALYSIS')
        self.assertEqual(result['target_id'],'mastersystem-'+self.digest[:12]);self.assertEqual(result['cpu'],'z80')
        c=sqlite3.connect(self.db)
        self.assertEqual(c.execute('SELECT isa FROM targets WHERE target_id=?',(result['target_id'],)).fetchone()[0],'z80')
        self.assertEqual(c.execute('SELECT COUNT(*) FROM native_preparations_v0403').fetchone()[0],1)
        c.close()

    def test_01b_megadrive_uses_same_registration_contract(self):
        md=self.roms/'Demo.md';rom=bytearray(0x4000)
        rom[0x100:0x104]=b'SEGA'
        md.write_bytes(rom);digest=sha256(md)
        c=connect(self.db);store_source(c,digest,md,len(rom),'SHA256_COMPLETE','megadrive','Demo','Mega Drive header');c.close()
        result=prepare(self.db,digest,self.dir/'md',allowed_roots=[self.roms],analyze=False)
        self.assertEqual(result['cpu'],'m68k')
        self.assertEqual(result['target_id'],'megadrive-'+digest[:12])
        c=sqlite3.connect(self.db)
        self.assertEqual(c.execute('SELECT COUNT(*) FROM targets WHERE target_id=?',(result['target_id'],)).fetchone()[0],1)
        self.assertEqual(c.execute('SELECT display_name FROM target_names WHERE target_id=?',(result['target_id'],)).fetchone()[0],'Demo')
        c.close()

    def test_02_wrong_rom_does_not_get_imported(self):
        self.sms.write_bytes(self.sms.read_bytes()[:-1]+b'\x7f')
        with self.assertRaisesRegex(ValueError,'SHA-256'):
            prepare(self.db,self.digest,self.dir/'output',allowed_roots=[self.roms])
        c=sqlite3.connect(self.db)
        self.assertEqual(c.execute("SELECT COUNT(*) FROM targets WHERE isa='z80'").fetchone()[0],0);c.close()

    def test_03_source_outside_rom_root_rejected(self):
        with self.assertRaisesRegex(ValueError,'outside'):
            prepare(self.db,self.digest,self.dir/'output',allowed_roots=[self.dir/'elsewhere'])

    def test_04_fake_ghidra_export_ingested_only_if_verified(self):
        # Tests the Ghidra *interface*, not claims about real Ghidra performance.
        stub=self.dir/'stub_ghidra.py'
        stub.write_text('''#!/usr/bin/env python3
import hashlib,json,sys,pathlib
args=sys.argv
idx=args.index('ExportFunctionBodies.java')
output=pathlib.Path(args[idx+1]);target=args[idx+2];sha=args[idx+3]
# The bytes are from the actual ROM fixture and never generated by the server.
raw=bytes.fromhex('3e01')
doc={'schema':'recomp-function-pcode-v1','target_id':target,
'source_sha256':sha,'analyzer':'ghidra-raw-pcode','language':'z80:LE:16:default',
'functions':[{'entry':0,'name':'recomp_seed_entry','body_min':0,'body_max':1,
'instructions':[{'address':0,'length':2,'bytes_sha256':hashlib.sha256(raw).hexdigest(),
'mnemonic':'LD','delay_slots':0,'call':False,'terminal':False,'flows':[],
'fallthrough':2,'pcode':[]}]}]}
output.write_text(json.dumps(doc))
''')
        stub.chmod(0o755)
        # Invoke the authored Python Ghidra fixture via Python on every OS.
        # A shebang-only .py file is not a Windows native executable.
        real_run=subprocess.run
        def run_fixture(argv, **kwargs):
            self.assertEqual(argv[0],str(stub))
            return real_run([sys.executable,*argv],**kwargs)
        with patch('nativeprep.engine.subprocess.run',side_effect=run_fixture):
            r=prepare(self.db,self.digest,self.dir/'out1',str(stub),[self.roms])
        self.assertEqual(r['status'],'CANDIDATES_RECOVERED_TRANSLATOR_NEEDED',r)
        self.assertEqual(r['candidates'],1)
        self.assertEqual(r['banked_bytes'],0x4000)
        c=sqlite3.connect(self.db)
        self.assertEqual(c.execute('SELECT COUNT(*) FROM native_function_candidates_v0403').fetchone()[0],1)
        c.close()
        with patch('nativeprep.engine.subprocess.run',side_effect=run_fixture):
            r2=prepare(self.db,self.digest,self.dir/'out2',str(stub),[self.roms])
        self.assertEqual(r2['candidates'],1)
        c=sqlite3.connect(self.db)
        self.assertEqual(c.execute('SELECT COUNT(*) FROM native_function_candidates_v0403').fetchone()[0],1)
        c.close()

    def test_05_unrecognised_image_recorded_as_unsupported(self):
        other=self.roms/'mystery.bin';other.write_bytes(b'other-data')
        digest=sha256(other)
        c=connect(self.db);store_source(c,digest,other,10,'SHA256_COMPLETE','unknown','Mystery','none');c.close()
        r=prepare(self.db,digest,self.dir/'other',[ ],[self.roms])
        self.assertEqual(r['status'],'NEEDS_EXECUTABLE_EXTRACTOR')
        self.assertIsNone(r['target_id'])
        c=sqlite3.connect(self.db)
        self.assertEqual(c.execute('SELECT COUNT(*) FROM native_preparations_v0403').fetchone()[0],1)
        c.close()

    def test_06_browser_action_end_to_end(self):
        with socket.socket() as sock:
            sock.bind(('127.0.0.1',0));port=sock.getsockname()[1]
        base=f'http://127.0.0.1:{port}'
        cmd=[sys.executable,str(ROOT/'recomp.py'),'--db',str(self.db),'serve',
             '--port',str(port),'--rom-root',str(self.roms),
             '--native-prepare-register-only']
        proc=subprocess.Popen(cmd,cwd=ROOT,stdout=subprocess.DEVNULL,stderr=subprocess.PIPE)
        self.addCleanup(lambda:proc.kill() if proc.poll() is None else None)
        token=None
        job_started=False
        try:
            for _ in range(200):
                try:
                    with urlopen(base+'/api/discovery-control',timeout=2) as resp:token=json.load(resp)['data']['token']
                    break
                except OSError:time.sleep(.04)
            else:self.fail('server failed to start')
            with urlopen(base+'/discovery') as resp:html=resp.read().decode()
            self.assertIn('id="prepare-run"',html)
            with urlopen(base+'/native') as resp:native=resp.read().decode()
            self.assertIn('id="prepared-native-targets"',native)
            payload=json.dumps({'source_id':self.digest}).encode()
            headers={'Content-Type':'application/json','Origin':base,'X-RecompDev-Token':token}
            request=Request(base+'/api/native-prepare-run',data=payload,headers=headers,method='POST')
            with urlopen(request,timeout=3) as resp:job=json.load(resp)['data']
            self.assertIn(job['state'],('RUNNING','COMPLETE'))
            job_started=True
            # Test the browser/worker contract without running real Ghidra.
            # A monotonic deadline avoids fixed-loop startup assumptions on Windows.
            deadline=time.monotonic()+45
            while job['state'] in ('RUNNING','STOP_REQUESTED') and time.monotonic()<deadline:
                time.sleep(.08)
                with urlopen(base+'/api/native-prepare-job',timeout=3) as resp:job=json.load(resp)['data']
            self.assertEqual(job['state'],'COMPLETE',job)
            self.assertIn('NATIVE_PREP_STATUS=REGISTERED_NEEDS_ANALYSIS',job['log'])
            with urlopen(base+'/api/native-preparation',timeout=3) as resp:d=json.load(resp)['data']
            self.assertEqual(len(d['targets']),1)
            self.assertEqual(d['targets'][0]['cpu'],'z80')
            self.assertTrue(job['report_written'])
            # CSRF token required for mutation, and source paths must be confined.
            req=Request(base+'/api/native-prepare-run',data=payload,
                  headers={**headers,'X-RecompDev-Token':'wrong'},method='POST')
            with self.assertRaises(HTTPError) as ctx:urlopen(req,timeout=3)
            self.assertEqual(ctx.exception.code,403)
            outside=self.dir/'out.sms';outside.write_bytes(b'foreign')
            digest=sha256(outside)
            c=connect(self.db);store_source(c,digest,outside,7,'SHA256_COMPLETE','mastersystem','Outside','none');c.close()
            req=Request(base+'/api/native-prepare-run',data=json.dumps({'source_id':digest}).encode(),headers=headers,method='POST')
            with self.assertRaises(HTTPError) as ctx:urlopen(req,timeout=3)
            self.assertEqual(ctx.exception.code,400)
        finally:
            # A failed assertion must not leave a worker holding worker.log open.
            if job_started and token:
                try:
                    with urlopen(base+'/api/native-prepare-job',timeout=2) as resp:
                        current=json.load(resp)['data']
                    if current['state']=='RUNNING':
                        req=Request(base+'/api/native-prepare-cancel',data=b'{}',
                            headers={'Content-Type':'application/json','Origin':base,
                                     'X-RecompDev-Token':token},method='POST')
                        with urlopen(req,timeout=3):pass
                    deadline=time.monotonic()+10
                    while current['state'] in ('RUNNING','STOP_REQUESTED') and time.monotonic()<deadline:
                        time.sleep(.1)
                        with urlopen(base+'/api/native-prepare-job',timeout=3) as resp:
                            current=json.load(resp)['data']
                except (OSError,ValueError):pass
            if proc.poll() is None:proc.terminate()
            try:proc.wait(timeout=5)
            except subprocess.TimeoutExpired:proc.kill();proc.wait()
            proc.stderr.close()

if __name__=='__main__':unittest.main()
