#!/usr/bin/env python3
"""Offline visual inspector for *actual captured* source-attested native frames.

Needs only Python's standard library. No ROM processing or CPU emulation; PPM
snapshots are generated by RecompDevNativeApp --snapshot-every N. Review sampled
output and event provenance; this cannot establish independent MAME parity.
"""
import argparse
import hashlib
import html
import json
import re
import struct
import sys
import webbrowser
import zlib
from pathlib import Path

def _chunk(tag,data):
    block=tag+data
    return struct.pack('!I',len(data))+block+struct.pack('!I',zlib.crc32(block)&0xffffffff)

def ppm_to_png(path,output):
    path=Path(path)
    raw=path.read_bytes()
    m=re.match(rb'P6\s+(\d{1,4})\s+(\d{1,4})\s+255\s',raw)
    if not m:raise ValueError('Invalid RGB P6 source frame')
    w,h=map(int,m.groups())
    if not 1<=w<=1024 or not 1<=h<=1024 or len(raw)!=m.end()+w*h*3:
        raise ValueError('Unbounded or incomplete frame image')
    pixels=raw[m.end():]
    scan=b''.join(b'\0'+pixels[r*w*3:(r+1)*w*3] for r in range(h))
    data=b'\x89PNG\r\n\x1a\n'+_chunk(b'IHDR',struct.pack('!IIBBBBB',w,h,8,2,0,0,0))
    data+=_chunk(b'IDAT',zlib.compress(scan,6))+_chunk(b'IEND',b'')
    output.write_bytes(data)
    return {'width':w,'height':h,'source_sha256':hashlib.sha256(raw).hexdigest()}

def generate(directory):
    directory=Path(directory).resolve(strict=True)
    if not directory.is_dir():raise ValueError('Expected a native capture directory')
    sources=sorted(p for p in directory.glob('native-frame-snapshot-??????.ppm') if not p.is_symlink())
    if not sources or len(sources)>128:raise ValueError('Expected 1 to 128 native frame snapshots')
    items=[]
    for p in sources:
        match=re.fullmatch(r'native-frame-snapshot-(\d{6})\.ppm',p.name)
        if not match:continue
        filename=p.with_suffix('.png')
        image=ppm_to_png(p,filename)
        items.append({'frame':int(match.group(1)),'filename':filename.name,**image})
    if not items:raise ValueError('No valid snapshots')
    out=directory/'native-frame-timeline.html'
    metadata={'schema':'recomp-native-timeline-v0443','images':items,
              'independent_reference_parity':'NOT_TESTED','gameplay':'NOT_ESTABLISHED'}
    (directory/'native-frame-timeline.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf-8')
    embedded=json.dumps(items).replace('<','\\u003c')
    out.write_text('''<!doctype html><html lang="en"><meta charset="utf-8">
<title>RecompDev Native Frame Timeline</title><style>
body{font:16px system-ui;background:#121821;color:#e9f1f7;margin:20px}
header{max-width:900px;margin:auto} .stage{display:flex;justify-content:center;margin:1em auto}
img{width:768px;max-width:94vw;aspect-ratio:4/3;image-rendering:pixelated;background:black}
input{width:100%}button{font:inherit;padding:8px;margin-right:8px}small{color:#a5b4c5}
</style><header><h2>RecompDev — guest-produced native frames</h2>
<p>Sampled capture only. Not an emulator, and not independent hardware parity.</p>
<div><button id="prev">Previous</button><button id="next">Next</button><strong id="label"></strong></div>
<input id="scrub" type="range" min="0" value="0" step="1" />
<small>Use Left/Right keys to inspect captured snapshots.</small>
</header><div class="stage"><img id="frame" alt="Guest-rendered native frame"></div>
<script>const items='''+embedded+''';
const scrub=document.getElementById('scrub'),frame=document.getElementById('frame'),label=document.getElementById('label');
scrub.max=items.length-1;
function show(i){i=Math.max(0,Math.min(i,items.length-1));scrub.value=i;
frame.src=items[i].filename;label.textContent=' Frame '+items[i].frame+' ('+(i+1)+'/'+items.length+')';}
scrub.oninput=()=>show(Number(scrub.value));
document.getElementById('prev').onclick=()=>show(Number(scrub.value)-1);
document.getElementById('next').onclick=()=>show(Number(scrub.value)+1);
document.addEventListener('keydown',e=>{if(e.key==='ArrowLeft')show(Number(scrub.value)-1);
else if(e.key==='ArrowRight')show(Number(scrub.value)+1);});show(0);
</script></html>''',encoding='utf-8')
    return out,metadata

def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--capture-dir',type=Path,required=True)
    p.add_argument('--open',action='store_true',help='Open the offline HTML viewer in your default browser')
    a=p.parse_args(argv)
    try:output,meta=generate(a.capture_dir)
    except (OSError,ValueError) as e:p.error(str(e))
    print('TIMELINE='+str(output),flush=True)
    print('SNAPSHOTS='+str(len(meta['images'])),flush=True)
    if a.open:webbrowser.open(output.as_uri())
    return 0
if __name__=='__main__':sys.exit(main())
