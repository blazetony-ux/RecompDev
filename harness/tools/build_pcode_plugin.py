#!/usr/bin/env python3
"""Adapt authentic RecompDev 0.4.0.45 Ghidra P-code exports into a DLL.

Calls the UNMODIFIED v0.4.0.45 verify_export and emit_instruction functions.
Does not analyze or invent instructions. Fails closed on ambiguous evidence.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT.parent/'legacy'/'RecompDev-v0.4.0.45'))
from nativepilot.generator import verify_export,emit_instruction  # noqa: E402

# v0.2 adapter only exposes AF,BC,DE,HL,SP and 64KiB unique temporaries.
# Other Z80 registers (IX/IY, shadow state, I/R, interrupt state) require ABI v2.
ALLOWED_MNEMONICS={'LD','JP','NOP','OUT','IN','INC','DEC','XOR','AND','OR','ADD','SUB','CP','JR','DJNZ'}
ALLOWED_OPS={'COPY','INT_AND','INT_OR','INT_LEFT','INT_ADD','INT_EQUAL','INT_RIGHT',
             'INT_SRIGHT','INT_SUB','INT_SLESS','INT_XOR','INT_NOTEQUAL','INT_ZEXT',
             'INT_2COMP','INT_CARRY','INT_SCARRY','INT_LESSEQUAL','INT_SBORROW',
             'BOOL_OR','BOOL_XOR','INT_LESS','BOOL_NEGATE','INT_NEGATE',
             'LOAD','STORE','BRANCH','CBRANCH','BRANCHIND'}

def safe_instruction(i):
    if i.get('mnemonic') not in ALLOWED_MNEMONICS:return 'mnemonic not supported by v0.2 execution bridge'
    for p in i.get('pcode',[]):
        if p.get('op') not in ALLOWED_OPS:return 'P-code operator requires unimplemented CPU state'
        for v in (p.get('inputs') or []) + ([p['output']] if p.get('output') is not None else []):
            off=v.get('offset'); size=v.get('size'); space=v.get('space')
            if type(off)!=int or type(size)!=int or not 1<=size<=8 or off<0:return 'invalid varnode'
            if space=='register' and not (off+size<=8 or (68<=off and off+size<=70)):
                return 'unmapped CPU register (IX/IY/shadow/interrupt)'
            if space=='unique' and off+size>65536:return 'unique temporary out of bounds'
    return None

def generate(rom,export,banks,destination,require_ghidra=False):
    rom=Path(rom).resolve(strict=True)
    destination=Path(destination)
    raw=rom.read_bytes()
    if len(raw)<0x4000 or len(raw)>64*1024*1024:raise ValueError('unsupported ROM size')
    doc=json.loads(Path(export).read_text(encoding='utf-8'))
    if doc.get('schema')!='recomp-function-pcode-v1':raise ValueError('unexpected export schema')
    if require_ghidra and doc.get('analyzer')!='ghidra-raw-pcode':
        raise ValueError('real-ROM mode requires an explicitly marked Ghidra P-code export')
    if not isinstance(doc.get('target_id'),str) or not doc['target_id']:raise ValueError('missing target identity')
    if doc.get('bank_context') is not None:raise ValueError('base export must have no bank overlay context')
    compiled,base_info,_=verify_export(doc,rom)
    bank_info=[]
    for bank in banks:
        bd=json.loads(Path(bank).read_text(encoding='utf-8'))
        if require_ghidra and bd.get('analyzer')!='ghidra-raw-pcode':
            raise ValueError('bank export must be marked as Ghidra P-code evidence')
        if bd.get('schema')!='recomp-function-pcode-v1' or bd.get('source_sha256')!=doc['source_sha256'] or bd.get('target_id')!=doc['target_id']:
            raise ValueError('bank export identity mismatch')
        if not bd.get('bank_context'):raise ValueError('bank overlay identity required')
        offsets,info,_=verify_export(bd,rom)
        for phys,i in offsets.items():
            if phys in compiled:
                if compiled[phys]!=i:raise ValueError('conflicting translated instruction at physical '+hex(phys))
            else:compiled[phys]=i
        bank_info.append({'bank_context':bd['bank_context'],'instructions':len(offsets),'candidates':info['candidates']})
    # Source-attested reset JP only when the producer supplies a valid P-code export.
    # Unlike v0445 nativepilot.generate_project, v0.2 does not synthesize reset instructions.
    code=['// Generated by v0.2 using RecompDev v0.4.0.45 production Ghidra P-code lowering.',
          '#include "rd_pcode_bridge.hpp"',
          '#include "nativepilot/z80_cycles.hpp"',
          '#include <array>',
          'namespace {',
          'int execute(uint32_t physical,RD_CpuState *cpu,const RD_Bus *bus,uint32_t *cycles){',
          ' if(!cpu||!bus||!cycles||!bus->read||!bus->write||!bus->in_port||!bus->out_port)return -1;',
          ' switch(physical){']
    failures=[];accepted=[]
    for physical,i in sorted(compiled.items()):
        reason=safe_instruction(i)
        if reason:
            failures.append({'physical':physical,'pc':i['address'],'reason':reason});continue
        try:lowered=emit_instruction(i)
        except (ValueError,TypeError,KeyError,IndexError) as e:
            failures.append({'physical':physical,'pc':i['address'],'reason':str(e)});continue
        # No implicit, unmodelled instruction: NOP has empty P-code by definition.
        if not lowered and i.get('mnemonic')!='NOP':
            failures.append({'physical':physical,'pc':i['address'],'reason':'no emitted semantics'});continue
        if len(lowered)>1000:
            failures.append({'physical':physical,'pc':i['address'],'reason':'lowered body too large'});continue
        pc=i['address'];n=i['length'];fb=i.get('fallthrough')
        fall=(pc+n)&0xffff if fb is None else fb
        if not (0<=fall<=65535):
            failures.append({'physical':physical,'pc':pc,'reason':'invalid fallthrough'});continue
        expected=raw[physical:physical+n]
        if physical+n>len(raw):raise ValueError('invalid attested physical interval')
        code.append(f' case 0x{physical:x}u: {{')
        code.append(f'  if(cpu->pc!=0x{pc:04x}u)return 0;')
        for offset,b in enumerate(expected):
            code.append(f'  if(bus->read(bus->ctx,uint16_t(cpu->pc+{offset}u))!=0x{b:02x}u)return -1;')
        code.append(f'  std::uint16_t next=0x{fall:04x}u;')
        code.append('  rd::BridgeState s(*cpu,*bus);')
        code.extend('  '+line for line in lowered)
        code.append('  const auto timing=recomp::z80::decode([&](std::uint16_t a){return bus->read(bus->ctx,a);},cpu->pc,next,std::uint16_t(0x%04xu));'%fall)
        # Timing unknown is a failure (no speculative approximate T-states).
        code.append('  if(!timing.known)return -1;')
        code.append('  s.commit();cpu->pc=next;*cycles=timing.tstates;return 1;')
        code.append(' }')
        accepted.append({'physical':physical,'pc':pc,'bytes':expected.hex(),'mnemonic':i.get('mnemonic'),
                         'source_bytes_sha256':i.get('bytes_sha256')})
    code+=[' default:return 0;',' }','}',
           'const RD_GameApi API={execute};',
           'const RD_Plugin PLUGIN={RD_ABI_VERSION,sizeof(RD_Plugin),RD_GAME,sizeof(API),"RecompDev v0.4.0.45 P-code generated game module",&API};',
           '}',
           'extern "C" RD_EXPORT const RD_Plugin *rd_get_plugin_v1(void){return &PLUGIN;}']
    # The exported identity is checked by the *host* against the entire ROM,
    # not merely against the source-byte guards at translated instructions.
    code.append('extern "C" RD_EXPORT const char* rd_game_source_sha256_v1(void){return "%s";}' % hashlib.sha256(raw).hexdigest())
    code.append('extern "C" RD_EXPORT uint64_t rd_game_source_size_v1(void){return %duLL;}' % len(raw))
    if not accepted:raise ValueError('no safe attested instructions qualified for compilation')
    destination.parent.mkdir(parents=True,exist_ok=True)
    destination.write_text('\n'.join(code)+'\n',encoding='utf-8')
    manifest={'schema':'recompdev-modular-game-v0.2','evidence_origin':'RecompDev v0.4.0.45 nativepilot.generator.verify_export + emit_instruction',
              'source_sha256':hashlib.sha256(raw).hexdigest(),'source_size':len(raw),'target_id':doc['target_id'],
              'translated_instructions':len(accepted),'rejected_instructions':len(failures),'attested_instructions':accepted,
              'rejections':failures,'bank_exports':bank_info,
              'limitations':['synthetic verification until owner supplies real Ghidra export',
                             'subset of Z80 register/interrupt semantics only',
                             'independent reference parity not established',
                             'full native gameplay and runtime-ROM independence not established']}
    (destination.parent/'game_module.manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    return manifest

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--require-ghidra',action='store_true',help='Refuse synthetic/other analyzer sources')
    parser.add_argument('--rom',required=True,type=Path)
    parser.add_argument('--export',required=True,type=Path)
    parser.add_argument('--bank-export',action='append',type=Path,default=[])
    parser.add_argument('--out',default=ROOT/'generated'/'rd_game_recomp_v0445.cpp',type=Path)
    opts=parser.parse_args()
    manifest=generate(opts.rom,opts.export,opts.bank_export,opts.out,opts.require_ghidra)
    print(json.dumps({k:manifest[k] for k in ('source_sha256','translated_instructions','rejected_instructions','bank_exports')},indent=2))
if __name__=='__main__':main()
